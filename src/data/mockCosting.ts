import type { CostingData, Ingredient, ItemCosting, Unit } from "@/data/costing";

const now = "2026-09-18T00:00:00.000Z";

function ing(name: string, qty: number, unit: Unit, unitCost: number, note = ""): Ingredient {
  return { id: `${name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${unit}`, name, qty, unit, unitCost, note };
}

function dish(cost: number, ingredients: Ingredient[], note?: string): ItemCosting {
  return { cost, ingredients, note, updatedAt: now };
}

function drink(glass: number, bottle: number, pours: number, ingredients: Ingredient[] = [], note?: string): ItemCosting {
  return { costs: { glass, bottle }, poursPerBottle: pours, ingredients, note, updatedAt: now };
}

